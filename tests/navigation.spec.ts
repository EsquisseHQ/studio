import { expect, test } from '@playwright/test'

test('header actions open pricing, saved renders and a persistent browser profile', async ({page}) => {
  await page.setViewportSize({width: 320, height: 800})
  await page.goto('/')
  await page.getByRole('link', {name: 'Upgrade'}).click()
  await expect(page).toHaveURL(/\/pricing$/)
  await page.getByRole('link', {name: 'My renders'}).click()
  await expect(page.getByRole('button', {name: 'My renders'})).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', {name: 'Account'}).click()
  await page.getByLabel('Display name').fill('Lou')
  await page.getByRole('button', {name: 'Save profile'}).click()
  await page.reload()
  await expect(page.getByRole('button', {name: 'Account'})).toHaveText('L')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('the home page explains the quote and opens the image studio', async ({page}) => {
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('heading', {name: 'Know the price before you create.'})).toBeVisible()
  await expect(page.locator('.home-hero a')).toHaveCount(1)
  await page.locator('#devis').scrollIntoViewIfNeeded()
  await expect(page.locator('#devis')).toBeInViewport()
  await expect(page.locator('#devis')).toContainText('Simulated studio fee')
  await page.getByRole('link', {name: 'Open Studio', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Image Studio'})).toBeVisible()
  await page.goto('/?model=flux')
  await expect(page.getByLabel('Model', {exact:true})).toHaveValue('flux')
})

test('MCP and community follow pricing on desktop and mobile', async ({page}) => {
  await page.goto('/pricing')
  const nav = page.getByRole('navigation', {name: 'Main navigation'})
  for (const width of [1280, 768, 320]) {
    await page.setViewportSize({width, height: 800})
    const links = await nav.getByRole('link').allTextContents()
    expect(links.slice(-3)).toEqual(['Pricing', 'MCP', 'Community ↗'])
    await expect(nav.getByRole('link', {name: 'Community ↗'})).toBeInViewport({ratio: 1})
    await expect(nav.getByRole('link', {name: 'Community ↗'})).toHaveAttribute('href', 'https://github.com/EsquisseHQ/studio/discussions')
  }
  await nav.getByRole('link', {name: 'MCP'}).click()
  await expect(page.getByRole('heading', {name: 'MCP for agents'})).toBeVisible()
  await expect(nav.getByRole('link', {name: 'MCP'})).toHaveAttribute('aria-current', 'page')
})

test('video and audio studies play and export on a small screen', async ({page}) => {
  await page.setViewportSize({width: 360, height: 800})
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.getByRole('button',{name:'Video menu'}).click()
  await page.getByRole('link',{name:/Vanishing Point/}).click()
  const video = page.locator('video')
  await expect(video).toHaveAttribute('src','/media/concrete.mp4')
  await video.evaluate(async (el: HTMLMediaElement) => {el.muted = true; await el.play()})
  await expect.poll(() => video.evaluate((el: HTMLMediaElement) => el.currentTime)).toBeGreaterThan(0)
  await page.getByRole('link',{name:'Audio',exact:true}).click()
  await page.getByRole('link',{name:/Frosted Glass/}).click()
  const audio = page.locator('audio')
  await audio.evaluate(async (el: HTMLMediaElement) => {el.muted = true; await el.play()})
  await expect.poll(() => audio.evaluate((el: HTMLMediaElement) => el.currentTime)).toBeGreaterThan(0)
  const file = page.waitForEvent('download')
  await page.getByRole('link',{name:'Download WAV'}).click()
  expect((await file).suggestedFilename()).toBe('glass.wav')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

