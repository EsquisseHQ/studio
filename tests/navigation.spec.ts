import { expect, test } from '@playwright/test'

test('the home page explains the quote and opens the image studio', async ({page}) => {
  await page.goto('/')
  await expect(page.getByRole('heading', {name: 'Crée en sachant ce que tu paies.'})).toBeVisible()
  await page.getByRole('link', {name: 'Voir un devis ↓'}).click()
  await expect(page.locator('#devis')).toBeInViewport()
  await expect(page.locator('#devis')).toContainText('Commission simulée')
  await page.getByRole('link', {name: 'Ouvrir le studio ↗'}).click()
  await expect(page.getByRole('heading', {name: 'Studio Image'})).toBeVisible()
  await page.goto('/?model=flux')
  await expect(page.getByLabel('Modèle', {exact:true})).toHaveValue('flux')
})

test('MCP and community follow pricing on desktop and mobile', async ({page}) => {
  await page.goto('/pricing')
  const nav = page.getByRole('navigation', {name: 'Navigation principale'})
  for (const width of [1280, 768, 320]) {
    await page.setViewportSize({width, height: 800})
    const links = await nav.getByRole('link').allTextContents()
    expect(links.slice(-3)).toEqual(['Pricing', 'MCP', 'Communauté ↗'])
    await expect(nav.getByRole('link', {name: 'Communauté ↗'})).toBeInViewport({ratio: 1})
    await expect(nav.getByRole('link', {name: 'Communauté ↗'})).toHaveAttribute('href', 'https://github.com/EsquisseHQ/studio/discussions')
  }
  await nav.getByRole('link', {name: 'MCP'}).click()
  await expect(page.getByRole('heading', {name: 'Studio MCP'})).toBeVisible()
  await expect(nav.getByRole('link', {name: 'MCP'})).toHaveAttribute('aria-current', 'page')
})

test('video and audio studies play and export on a small screen', async ({page}) => {
  await page.setViewportSize({width: 360, height: 800})
  await page.goto('/')
  await page.getByRole('button',{name:'Menu Vidéo'}).click()
  await page.getByRole('link',{name:/Ligne de fuite/}).click()
  const video = page.locator('video')
  await expect(video).toHaveAttribute('src','/media/concrete.mp4')
  await video.evaluate(async (el: HTMLMediaElement) => {el.muted = true; await el.play()})
  await expect.poll(() => video.evaluate((el: HTMLMediaElement) => el.currentTime)).toBeGreaterThan(0)
  await page.getByRole('link',{name:'Audio',exact:true}).click()
  await page.getByRole('link',{name:/Verre dépoli/}).click()
  const audio = page.locator('audio')
  await audio.evaluate(async (el: HTMLMediaElement) => {el.muted = true; await el.play()})
  await expect.poll(() => audio.evaluate((el: HTMLMediaElement) => el.currentTime)).toBeGreaterThan(0)
  const file = page.waitForEvent('download')
  await page.getByRole('link',{name:'Télécharger le WAV'}).click()
  expect((await file).suggestedFilename()).toBe('glass.wav')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('catalog discovery, comparison and pricing lead to the selected image model', async ({page}) => {
  await page.goto('/models')
  await page.getByRole('button',{name:'Vidéo',exact:true}).click()
  await expect(page.locator('.model-card')).toHaveCount(1)
  await page.getByRole('button',{name:'Tout',exact:true}).click()
  await page.getByRole('searchbox').fill('black forest')
  await expect(page.locator('.model-card')).toHaveCount(1)
  await page.getByRole('link',{name:'Fournisseurs',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Black Forest Labs'})).toBeVisible()
  await page.getByRole('link',{name:'Comparer',exact:true}).click()
  await page.getByLabel('Modèle 1').selectOption('sound')
  await expect(page.getByRole('cell',{name:'WAV',exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Pricing',exact:true}).click()
  await expect(page.getByText('Total indicatif HT')).toBeVisible()
  await page.getByRole('link',{name:/Ouvrir le devis/}).click()
  await expect(page.getByLabel('Modèle',{exact:true})).toHaveValue('flux')
})
